import assert from 'node:assert/strict';
const elements=new Map();
const el=id=>{if(!elements.has(id))elements.set(id,{disabled:false,textContent:'',classList:{add(){},remove(){}}});return elements.get(id);};
globalThis.document={getElementById:el};
let timers=new Map(), tid=0;
globalThis.setTimeout=(fn,ms)=>{timers.set(++tid,{fn,ms});return tid;};
globalThis.clearTimeout=id=>timers.delete(id);
const calls=[];
let data={available:true,accepted:true,service:'/bag/recording_status',phase:'idle'}, pending=null, fail=false, pendingCommand=null;
globalThis.fetch=async(url,options)=>{
 calls.push({url,body:JSON.parse(options.body)});
 if(pending && url.endsWith('_status'))return new Promise(resolve=>pending.resolve=resolve);
 if(pendingCommand && url.endsWith('_start'))return new Promise(resolve=>pendingCommand.resolve=resolve);
 if(fail)throw Error('outcome unknown');
 return {ok:true,json:async()=>({...data})};
};
const {connectRecording,disconnectRecording}=await import('../frontend/recording.js');
const flush=async()=>{for(let i=0;i<4;i++)await new Promise(r=>setImmediate(r));};
assert.equal(calls.length,0);
connectRecording({connection:{host:'jetson'},container:'abc'});await flush();
assert.equal(el('recording-start').disabled,false);
data.phase='recording'; await el('recording-refresh').onclick();await flush();
assert.equal(el('recording-start').disabled,true);
assert.equal(el('recording-stop').disabled,false);
pending={};el('recording-refresh').onclick();await flush();
assert.equal(el('recording-refresh').disabled,true);
assert.match(el('recording-refresh').textContent,/取得中/);
assert.match(el('recording-event').textContent,/ボタンを受け付け/);
const before=calls.length;
el('recording-refresh').onclick();await flush();
assert.equal(calls.length,before,'refresh cannot overlap an existing poll');
data.phase='stopping';await el('recording-stop').onclick();
assert.equal(calls.at(-1).body.recording_service,'/bag/recording_status');
pending.resolve({ok:true,json:async()=>({...data,phase:'idle'})});pending=null;await flush();
assert.match(el('recording-state').textContent,/停止処理中/);
assert.equal(el('recording-start').disabled,true);
fail=true;await el('recording-stop').onclick();
assert.match(el('recording-event').textContent,/outcome unknown/);
assert.equal(calls.filter(c=>c.url.endsWith('_stop')).length,2,'one call per explicit click');
assert.equal(el('recording-stop').disabled,true);
fail=false;data.phase='idle';await el('recording-refresh').onclick();await flush();
const now=Date.now;Date.now=()=>now()+9000;
await el('recording-start').onclick();
assert.equal(calls.filter(c=>c.url.endsWith('_start')).length,0,'expired status cannot send');
Date.now=now;
pendingCommand={};
const start=el('recording-start').onclick();await flush();
assert.match(el('recording-start').textContent,/送信中/);
assert.match(el('recording-state').textContent,/開始要求を送信中/);
pendingCommand.resolve({ok:true,json:async()=>({...data,phase:'recording'})});
await start;pendingCommand=null;
assert.match(el('recording-event').textContent,/要求を受け付け/);
data={available:false,message:'録画manager未検出'};
await el('recording-refresh').onclick();
assert.equal(el('recording-start').disabled,true);
assert.match(el('recording-state').textContent,/未検出/);
assert.match(el('recording-warning').textContent,/正常に取得するまで/);
fail=true;await el('recording-refresh').onclick();fail=false;
assert.match(el('recording-event').textContent,/outcome unknown/);
assert.match(el('recording-state').textContent,/失敗/);
assert.equal(el('recording-refresh').disabled,false);
pending={};el('recording-refresh').onclick();await flush();disconnectRecording();
pending.resolve({ok:true,json:async()=>data});await flush();
assert.equal(el('recording-start').disabled,true);
console.log('Recording UI: shared status, stopping, stale responses, unknown outcomes, expiry, disconnect passed');
